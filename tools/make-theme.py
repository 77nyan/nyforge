#!/usr/bin/env python3
"""Generates the NyBoot menu theme (assets/grub/theme/*) and the list that embeds it.

The committed outputs are what `cargo build` embeds; normal users never run this.
Needs: Pillow, grub-mkfont (grub-common).  Run:  python3 tools/make-theme.py

The look is deliberately plain: one flat grey, square corners, a thin border, Liberation Sans.
It writes three sizes of the same theme (theme.txt for 1080p and smaller (about 100% scaling), theme-large.txt for 1440p (about 125%),
theme-xlarge.txt for 4K (about 175%)); the menu script picks one from the screen mode it managed to set.
"""
import os
import re
import subprocess
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "grub", "theme")
FONTS = os.path.join(ROOT, "assets", "fonts")
ASSETS_RS = os.path.join(ROOT, "crates", "nyforge-core", "src", "nyboot", "assets.rs")
os.makedirs(OUT, exist_ok=True)

# Palette. The page is one flat grey; the list is a slightly darker panel with a hairline border.
PAGE = (0x2b, 0x2f, 0x39)      # #2b2f39
PANEL = (0x23, 0x26, 0x2e)     # #23262e
BORDER = (0x40, 0x46, 0x53)    # #404653
SELECT = (0x3a, 0x40, 0x4e)    # #3a404e  selected row
ACCENT = (0x3d, 0x93, 0xf5)    # #3d93f5  thin marker on the selected row
THUMB = (0x6c, 0x74, 0x86)
TRACK = (0x32, 0x37, 0x42)

# name suffix -> scale. Sizes below are the 1080p design values times the scale.
TIERS = {"": 1.0, "-large": 1.25, "-xlarge": 1.75}


def save(img, name):
    img.save(os.path.join(OUT, name), optimize=True)


def px(color, w=1, h=1):
    return Image.new("RGB", (w, h), color)


def frame(prefix, fill, edge, b):
    """Square nine-slice: a border b pixels thick around a flat fill."""
    for k in ("nw", "ne", "sw", "se"):
        save(px(edge, b, b), f"{prefix}_{k}.png")
    for k in ("n", "s"):
        save(px(edge, 1, b), f"{prefix}_{k}.png")
    for k in ("w", "e"):
        save(px(edge, b, 1), f"{prefix}_{k}.png")
    save(px(fill), f"{prefix}_c.png")


def pieces():
    for suf, sc in TIERS.items():
        t = suf.replace("-", "_")
        b = max(1, round(sc))
        row = round(46 * sc)
        frame(f"menu{t}", PANEL, BORDER, b)
        frame(f"terminal_box{t}", (0x16, 0x19, 0x1f), BORDER, b)
        # Selected row: a flat lighter bar with an accent marker on its left edge.
        cap = round(14 * sc)
        w = Image.new("RGB", (cap, row), SELECT)
        w.paste(px(ACCENT, round(3 * sc), row), (0, 0))
        save(w, f"select{t}_w.png")
        save(px(SELECT, 1, row), f"select{t}_c.png")
        save(px(SELECT, cap, row), f"select{t}_e.png")
        # Scrollbar: slim, square.
        for k in ("c", "n", "s"):
            save(px(TRACK), f"scrollbar_frame{t}_{k}.png")
            save(px(THUMB), f"scrollbar_thumb{t}_{k}.png")


# Latin + Latin Extended, Greek, Cyrillic, bullets and arrows. Anything else falls back to unicode.pf2.
RANGES = "0x20-0x7e,0xa0-0x24f,0x370-0x3ff,0x400-0x4ff,0x2022-0x2022,0x2190-0x2193"


def fonts():
    reg = os.path.join(FONTS, "LiberationSans-Regular.ttf")
    semi = os.path.join(FONTS, "LiberationSans-Bold.ttf")
    want = set()
    for sc in TIERS.values():
        want |= {("Regular", round(15 * sc)), ("Regular", round(17 * sc)), ("Regular", round(24 * sc)), ("Bold", round(24 * sc))}
    for style, sz in sorted(want):
        out = os.path.join(OUT, f"font-{style.lower()}-{sz}.pf2")
        subprocess.check_call(["grub-mkfont", "-s", str(sz), "-r", RANGES, "-o", out,
                               reg if style == "Regular" else semi], stderr=subprocess.DEVNULL)


THEME = """# NyBoot menu theme (generated by tools/make-theme.py): one flat grey, square corners, Liberation Sans (SIL OFL).
# Positions are percentages so it fits any screen; font sizes are fixed, so there is one file per size.

title-text: ""
desktop-color: "#2b2f39"

terminal-font: "GNU Unifont Regular 16"
terminal-left: "10%"
terminal-top: "10%"
terminal-width: "80%"
terminal-height: "80%"
terminal-border: "0"
terminal-box: "terminal_box{t}_*.png"

# Shortcuts, top left, small.
+ label {{
    id = "keys"
    left = {kl}
    top = 100%-{kb}
    width = 70%
    height = {kh}
    text = "↑ ↓  Choose     Enter  Start     E  Edit     C  Command line"
    font = "Liberation Sans Regular {f13}"
    color = "#8e96a6"
    align = "left"
}}

# The list.
+ boot_menu {{
    left = 15%
    top = 12%
    width = 70%
    height = 76%
    item_font = "Liberation Sans Regular {f18}"
    selected_item_font = "Liberation Sans Bold {f18}"
    item_color = "#d3d7de"
    selected_item_color = "#ffffff"
    icon_width = 0
    icon_height = 0
    item_icon_space = 0
    item_height = {row}
    item_padding = {pad}
    item_spacing = {gap}
    menu_pixmap_style = "menu{t}_*.png"
    selected_item_pixmap_style = "select{t}_*.png"
    scrollbar = true
    scrollbar_width = {sbw}
    scrollbar_thumb = "scrollbar_thumb{t}_*.png"
    scrollbar_frame = "scrollbar_frame{t}_*.png"
}}

# Countdown (only shown when a timeout is set).
+ label {{
    id = "__timeout__"
    left = 0
    top = 90%
    width = 100%
    height = {th}
    text = "Starting automatically in %d seconds"
    font = "Liberation Sans Regular {f14}"
    color = "#8e96a6"
    align = "center"
}}
"""


def themes():
    for suf, sc in TIERS.items():
        txt = THEME.format(
            t=suf.replace("-", "_"), kl=round(24 * sc), kb=round(52 * sc), kh=round(24 * sc),
            f13=round(15 * sc), f14=round(17 * sc), f18=round(24 * sc), row=round(46 * sc),
            pad=round(12 * sc), gap=round(2 * sc), sbw=round(6 * sc), th=round(24 * sc))
        open(os.path.join(OUT, f"theme{suf}.txt"), "w").write(txt)


def embed_list():
    files = sorted(os.path.relpath(os.path.join(dp, f), OUT).replace(os.sep, "/") for dp, _, fs in os.walk(OUT) for f in fs)
    body = "".join(f'    ("{f}", include_bytes!("../../../../assets/grub/theme/{f}")),\n' for f in files)
    block = ("// THEME_FILES-BEGIN (written by tools/make-theme.py)\n"
             "pub const THEME_FILES: &[(&str, &[u8])] = &[\n" + body + "];\n// THEME_FILES-END\n")
    s = open(ASSETS_RS).read()
    s = re.sub(r"// THEME_FILES-BEGIN.*?// THEME_FILES-END\n", lambda m: block, s, flags=re.S)
    open(ASSETS_RS, "w").write(s)


if __name__ == "__main__":
    keep = set()
    for dp, _, fs in os.walk(OUT):
        for f in fs:
            if f not in keep:
                os.remove(os.path.join(dp, f))
    pieces()
    fonts()
    themes()
    embed_list()
    total = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(OUT) for f in fs)
    print(f"theme assets: {total / 1024:.0f} KiB in {OUT}")
